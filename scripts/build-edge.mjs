// Bundles edge/sports.ts + the shared lib/ code into one file for the Supabase Edge Function.
// Run: npm run build:edge  →  supabase/functions/sports/index.ts (commit it; it's what gets deployed)
import { build } from "esbuild";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SUPABASE_JS = "npm:@supabase/supabase-js@" + JSON.parse(await readFile(new URL("../node_modules/@supabase/supabase-js/package.json", import.meta.url), "utf8")).version;

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

// The edge runtime is Deno: give the bundled Node-style code its `process.env` and `Buffer`.
// Non-secret settings default here; Supabase secrets with the same name override them.
const banner = `// GENERATED by scripts/build-edge.mjs from edge/sports.ts. Do not edit by hand.
// deno-lint-ignore-file
// @ts-nocheck
import { Buffer } from "node:buffer";
const __env = (k) => globalThis.Deno?.env.get(k);
const process = { env: new Proxy({
  NODE_ENV: "production",
  RESEND_FROM: "Janobi Sports <sports@outreach.janobi.agency>",
  LEAD_NOTIFY_EMAIL: "wajeeh@janobi.agency",
  NEXT_PUBLIC_CAL_LINK: "wajeehfromjanobi/brand-audit",
  NEXT_PUBLIC_CAL_ORIGIN: "https://app.cal.com",
}, { get: (d, k) => (k === "NODE_ENV" ? d[k] : __env(k) ?? d[k]) }) };
`;

await build({
  entryPoints: [path.join(root, "edge/sports.ts")],
  outfile: path.join(root, "supabase/functions/sports/index.ts"),
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  mainFields: ["module", "main"],
  conditions: ["worker", "browser"],
  external: ["node:*", "npm:*"],
  // Deno fetches supabase-js itself, so the bundle stays small.
  plugins: [
    {
      name: "supabase-npm",
      setup(b) {
        b.onResolve({ filter: /^@supabase\/supabase-js$/ }, () => ({ path: SUPABASE_JS, external: true }));
      },
    },
  ],
  alias: { "@": root, "server-only": path.join(root, "test/empty.ts") },
  banner: { js: banner },
  legalComments: "none",
  logLevel: "info",
});
